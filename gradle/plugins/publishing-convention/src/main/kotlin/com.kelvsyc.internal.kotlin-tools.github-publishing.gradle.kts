import groovy.json.JsonOutput
import groovy.json.JsonSlurper

plugins {
    `maven-publish`
}

publishing {
    repositories.maven("https://maven.pkg.github.com/kelvSYC/kotlin-tools") {
        name = "GitHubPackages"
        credentials {
            username = System.getenv("GITHUB_ACTOR")
            password = System.getenv("GITHUB_TOKEN")
        }
    }

    publications.withType<MavenPublication>().configureEach {
        // Publish resolved versions. Dependencies declared without a version (versions from the internal platform,
        // which is stripped below; Kotlin core libraries such as kotlin-reflect; other cores via included builds)
        // would otherwise be published versionless and be unresolvable for consumers.
        // Kotlin Multiplatform target publications (e.g. `js`) are generated by the Kotlin Gradle plugin and do not
        // honour this mapping.
        versionMapping {
            allVariants {
                fromResolutionResult()
            }
        }
        pom.withXml {
            StripInternalPlatform.fromPom(asNode())
        }
    }
}

tasks.withType<GenerateModuleMetadata>().configureEach {
    doLast(StripInternalPlatform.ModuleMetadataAction())
}
